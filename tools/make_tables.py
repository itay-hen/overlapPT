#!/usr/bin/env python3
"""Generate hamiltonian2.hpp: PMR tables for H1 and H2 on ONE shared permutation list.

prepare.cpp builds hamiltonian.hpp (N, Nop, P_matrix, cycles, and H1's own
tables) from H1.txt.  The overlap code needs both Hamiltonians expressed against
that same P_matrix list, with H2 simply having no off-diagonal term (d = 0) on
permutations it lacks, e.g. the bonds removed by severing.  prepare.cpp cannot
do this itself, since it drops zero-coefficient terms.

Supported terms: products of Z's (diagonal) or products of X's (off-diagonal),
one per line in prepare.cpp's "coeff i P j P ..." format.  Every permutation used
by H2 must also appear in H1 (H1 should be the full Hamiltonian).

Table semantics match the generated code exactly:
    E(z)   = - sum_k sign_k * c_k,   sign_k = 2*(popcount(mask_k & ~z) % 2) - 1
    d_j(z) = same formula over the terms attached to permutation j, evaluated at
             the state AFTER applying P_j (RenyiReplica::calc_d_for_config).

Also emits the normalized traces used by the beta -> 0 anchor:
    OV_TR_H[a]     = Tr(H_a) / 2^N        (coefficient of the identity)
    OV_TR_HH[a][b] = Tr(H_a H_b) / 2^N    (sum over Pauli strings of c_a * c_b)

Usage:  python3 tools/make_tables.py hamiltonian.hpp H1.txt H2.txt > hamiltonian2.hpp
"""
import re
import sys
from collections import defaultdict


def parse_P_matrix(hpp):
    txt = open(hpp).read()
    N = int(re.search(r'#define\s+N\s+(\d+)', txt).group(1))
    Nop = int(re.search(r'#define\s+Nop\s+(\d+)', txt).group(1))
    body = re.search(r'P_matrix\[Nop\]\s*=\s*\{(.*?)\};', txt, re.S).group(1)
    masks = [int(s, 2) for s in re.findall(r'bitset<N>\("([01]+)"\)', body)]
    assert len(masks) == Nop, (len(masks), Nop)
    return N, masks


def parse_terms(path, N):
    terms = []
    for ln, line in enumerate(open(path), 1):
        tok = line.split()
        if not tok:
            continue
        c = float(tok[0])
        if c == 0.0:
            continue
        if len(tok) % 2 == 0:
            raise SystemExit(f'{path}:{ln}: expected "coeff i P j P ..."')
        xm = zm = 0
        pauli = {}
        for i in range(1, len(tok), 2):
            q, p = int(tok[i]), tok[i + 1].upper()
            if not 1 <= q <= N:
                raise SystemExit(f'{path}:{ln}: qubit {q} out of range 1..{N}')
            if q in pauli:
                raise SystemExit(f'{path}:{ln}: qubit {q} repeated')
            pauli[q] = p
            if p == 'X':
                xm |= 1 << (q - 1)
            elif p == 'Z':
                zm |= 1 << (q - 1)
            else:
                raise SystemExit(f'{path}:{ln}: only X and Z terms are supported (got {p})')
        if xm and zm:
            raise SystemExit(f'{path}:{ln}: mixed X/Z terms are not supported')
        terms.append((c, xm, zm, tuple(sorted(pauli.items()))))
    return terms


def check_signs(terms, path):
    """Enforce Prop. 2 (positivity): every off-diagonal amplitude must be <= 0.

    For the supported term types an X-string term c * X_T contributes d = c at every
    configuration, so the net coefficient of each X-string must be <= 0. A positive
    amplitude makes weights negative; the sampler (absolute values in Metropolis) and
    MBAR (negative weights discarded) would then silently target the wrong ensemble.
    """
    net = defaultdict(float)
    for c, xm, zm, _ in terms:
        if xm:
            net[xm] += c
    bad = [(xm, c) for xm, c in net.items() if c > 0]
    if bad:
        raise SystemExit(f'{path}: positive off-diagonal coefficient(s) {[c for _, c in bad]} -- '
                         'the method requires d <= 0 (stoquastic in this basis, Prop. 2)')


def tables(terms, masks):
    d0 = []
    d = [[] for _ in masks]
    for c, xm, zm, _ in terms:
        if xm == 0:
            d0.append((c, zm))
        else:
            if xm not in masks:
                raise SystemExit('a permutation of this Hamiltonian is missing from P_matrix '
                                 '(H1 must contain every off-diagonal term of H2)')
            d[masks.index(xm)].append((c, 0))
    return d0, d


def pauli_dict(terms):
    out = defaultdict(float)
    for c, _, _, key in terms:
        out[key] += c
    return out


def bs(m, N):
    return f'std::bitset<N>("{format(m, "0" + str(N) + "b")}")'


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    N, masks = parse_P_matrix(sys.argv[1])
    T = [parse_terms(p, N) for p in sys.argv[2:4]]
    for t, path in zip(T, sys.argv[2:4]):
        check_signs(t, path)
    tabs = [tables(t, masks) for t in T]
    pd = [pauli_dict(t) for t in T]
    Nop = len(masks)
    d0max = max(1, max(len(t[0]) for t in tabs))
    dmax = max(1, max(len(x) for t in tabs for x in t[1]))

    o = []
    o.append('// Generated by tools/make_tables.py -- do not edit by hand.')
    o.append(f'// Sources: {sys.argv[1]} (P_matrix), H1 = {sys.argv[2]}, H2 = {sys.argv[3]}')
    o.append('#define OV_NHAM 2')
    o.append(f'const int OV_D0_maxsize = {d0max};')
    o.append(f'const int OV_D_maxsize = {dmax};')
    o.append('const int OV_D0_size[OV_NHAM] = {' + ', '.join(str(len(t[0])) for t in tabs) + '};')

    def pad(lst, n, fill):
        return lst + [fill] * (n - len(lst))

    o.append('const double OV_D0_coeff[OV_NHAM][OV_D0_maxsize] = {' + ', '.join(
        '{' + ', '.join(repr(c) for c, _ in pad(t[0], d0max, (0.0, 0))) + '}' for t in tabs) + '};')
    o.append('const std::bitset<N> OV_D0_product[OV_NHAM][OV_D0_maxsize] = {' + ', '.join(
        '{' + ', '.join(bs(m, N) for _, m in pad(t[0], d0max, (0.0, 0))) + '}' for t in tabs) + '};')
    o.append('const int OV_D_size[OV_NHAM][Nop] = {' + ', '.join(
        '{' + ', '.join(str(len(x)) for x in t[1]) + '}' for t in tabs) + '};')
    o.append('const double OV_D_coeff[OV_NHAM][Nop][OV_D_maxsize] = {' + ', '.join(
        '{' + ', '.join('{' + ', '.join(repr(c) for c, _ in pad(x, dmax, (0.0, 0))) + '}' for x in t[1]) + '}'
        for t in tabs) + '};')
    o.append('const std::bitset<N> OV_D_product[OV_NHAM][Nop][OV_D_maxsize] = {' + ', '.join(
        '{' + ', '.join('{' + ', '.join(bs(m, N) for _, m in pad(x, dmax, (0.0, 0))) + '}' for x in t[1]) + '}'
        for t in tabs) + '};')
    ident = ()
    o.append('const double OV_TR_H[OV_NHAM] = {' + ', '.join(repr(p.get(ident, 0.0)) for p in pd) + '};')
    hh = [[sum(pa[k] * pb.get(k, 0.0) for k in pa) for pb in pd] for pa in pd]
    o.append('const double OV_TR_HH[OV_NHAM][OV_NHAM] = {' + ', '.join(
        '{' + ', '.join(repr(v) for v in row) + '}' for row in hh) + '};')
    n_removed = sum(1 for j in range(Nop) if tabs[0][1][j] and not tabs[1][1][j])
    o.append(f'// {Nop} permutations; {n_removed} have an off-diagonal term in H1 but not in H2.')
    # [OV_CUT_FLIP] Side of the cut: the connected component of H2's interaction graph
    # (qubits linked when they share a term) that contains the highest-index qubit. Flipping
    # it is the block move of replica.hpp; 0 when H2 is connected (move then disabled).
    parent = list(range(N))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for c, xm, zm, _ in T[1]:
        qs = [i for i in range(N) if (xm | zm) >> i & 1]
        for a, b in zip(qs, qs[1:]):
            parent[find(a)] = find(b)
    root = find(N - 1)
    side = sum(1 << i for i in range(N) if find(i) == root)
    if side == (1 << N) - 1:
        side = 0
    o.append(f'const std::bitset<N> OV_CUT_MASK = {bs(side, N)};   // {bin(side).count("1")} qubits')
    # [OV_CUT_FLIP_ALL] every connected component of H2's interaction graph (empty list when
    # H2 is connected); replica.hpp flips one, chosen uniformly, when OV_CUT_FLIP_ALL is set.
    roots = sorted({find(i) for i in range(N)})
    comps = [sum(1 << i for i in range(N) if find(i) == r) for r in roots] if len(roots) > 1 else []
    o.append(f'const int OV_NCUT = {len(comps)};')
    o.append('const std::bitset<N> OV_CUT_MASKS[' + str(max(1, len(comps))) + '] = {' +
             ', '.join(bs(c, N) for c in (comps or [0])) + '};   // sizes ' +
             ' '.join(str(bin(c).count('1')) for c in comps))
    print('\n'.join(o))


if __name__ == '__main__':
    main()
